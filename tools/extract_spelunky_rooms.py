#!/usr/bin/env python3
"""Extracts authentic 10x8 room templates from GDSpelunky's level_generation.gd."""

import os
import re

SRC = r"C:\Users\memor\.gemini\antigravity\brain\bed346dc-5c9f-41e3-a887-370223bde575\scratch\gdspelunky\scripts\default_scripts\level_generation.gd"
OUT = os.path.join("runtime", "game", "spelunky_rooms.h")


def classify_branch(fn, cond, subcond):
    if fn == "scr_room_gen5":
        return "boss_top" if "y < 480" in cond else "boss_bot"
    if "start_room_x" in cond:
        return "start_drop" if "room_path == 2" in subcond else "start"
    if "end_room_x" in cond:
        return "end_from_top" if "room_path_above == 2" in subcond else "end"
    if "room_path == 4" in cond:
        return "shop_left"
    if "room_path == 5" in cond:
        return "shop_right"
    if "room_path == 6" in cond:
        return "special"
    if "room_path == 7" in cond:
        return "pit_top"
    if "room_path == 8" in cond:
        return "pit_mid"
    if "room_path == 9" in cond:
        return "pit_bot"
    if "room_path == 3" in cond:
        return "land"
    if "room_path == 0 or room_path == 1" in cond or "room_path == 1" in cond:
        return "main"
    if "room_path == 0" in cond:
        return "side"
    if cond.startswith("else:"):
        return "drop"
    return "main"


def main():
    lines = open(SRC, encoding="utf-8").readlines()
    fn = None
    cond = ""
    subcond = ""
    # area_key -> bucket -> list of 80-char strings
    fn_map = {
        "scr_room_gen": "mines",
        "scr_room_gen2": "lush",
        "scr_room_gen3": "ice",
        "scr_room_gen4": "temple",
        "scr_room_gen5": "olmec",
        "scr_room_gen_market": "market",
        "scr_room_gen_yeti": "yeti",
    }
    data = {v: {} for v in fn_map.values()}

    for line in lines:
        s = line.strip()
        if s.startswith("func "):
            name = s.split("(")[0][5:]
            fn = fn_map.get(name)
            cond = ""
            subcond = ""
            continue
        if not fn:
            continue
        # Top-level branch inside function (1 tab)
        if line.startswith("\tif ") or line.startswith("\telif ") or line.startswith("\telse:"):
            cond = s
            subcond = ""
        elif line.startswith("\t\tif ") or line.startswith("\t\telif ") or line.startswith("\t\telse:"):
            subcond = s

        m = re.search(r'str_temp\s*=\s*"([^"]{80})"', s)
        if m and cond:
            b = classify_branch(
                "scr_room_gen5" if fn == "olmec" else fn, cond, subcond
            )
            tpl = m.group(1)
            lst = data[fn].setdefault(b, [])
            if tpl not in lst:
                lst.append(tpl)

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Auto-generated by tools/extract_spelunky_rooms.py. Do not edit by hand. */\n")
        f.write("#ifndef SPELUNKY_ROOMS_H\n")
        f.write("#define SPELUNKY_ROOMS_H\n\n")
        for area, buckets in data.items():
            for bucket, tpls in sorted(buckets.items()):
                arr = f"g_rooms_{area}_{bucket}"
                f.write(f"static const char *const {arr}[] = {{\n")
                for t in tpls:
                    esc = t.replace("\\", "\\\\").replace('"', '\\"')
                    f.write(f'    "{esc}",\n')
                f.write("};\n")
                f.write(f"#define {arr.upper()}_COUNT {len(tpls)}\n\n")
        f.write("#endif\n")

    total = sum(len(v) for b in data.values() for v in b.values())
    print(f"Wrote {OUT} with {total} room templates across {len(data)} sets.")
    for area, buckets in data.items():
        summary = ", ".join(f"{k}:{len(v)}" for k, v in sorted(buckets.items()))
        print(f"  {area}: {summary}")


if __name__ == "__main__":
    main()
